#!/usr/bin/env python3
"""Compare Gemini and Tesseract outputs with the hand-written ground truth.

Usage:
    python experiments/evaluate.py          # writes experiments/RESULTS.md

Each extracted field is classified as:
    correct       value matches what is printed on the document
    abstained_ok  nothing printed and the method returned nothing
    missed        something printed, method returned nothing   (safe: goes to review)
    wrong         method returned a different value            (DANGEROUS)
    invented      nothing printed, method returned a value     (DANGEROUS)
"""
from __future__ import annotations

import json
from datetime import date

from common import (EXPERIMENT_DIR, FIELDS, RESULTS_DIR, canonical_cert_type, load_ground_truth,
                    load_records, load_workers, name_key, normalize_date)
from validation import check_record

METHODS = ["gemini", "tesseract"]
DANGEROUS = {"wrong", "invented"}
OK = {"correct", "abstained_ok"}
LABELS = {"worker_name": "Name", "certificate_type": "Type", "issue_date": "Issue date",
          "expiry_date": "Expiry date"}


def truth_value(field: str, raw: str):
    if not raw:
        return None
    if field.endswith("_date"):
        return normalize_date(raw)
    if field == "certificate_type":
        return canonical_cert_type(raw)
    return raw


def same(field: str, truth, pred) -> bool:
    if field == "worker_name":
        return name_key(truth) == name_key(pred)
    return truth == pred


def classify(field: str, truth, pred) -> str:
    if truth is None:
        return "abstained_ok" if pred is None else "invented"
    if pred is None:
        return "missed"
    return "correct" if same(field, truth, pred) else "wrong"


def evaluate(gt: dict, records: dict, workers: list[str]) -> dict:
    rows, per_field = [], {f: {} for f in FIELDS}
    unreadable_total = unreadable_flagged = 0
    dangerous_total = dangerous_caught = 0
    latencies = []
    for file, truth in gt.items():
        rec = records.get(file)
        if rec is None:
            continue
        latencies.append(rec.get("latency_s", 0))
        truly_unreadable = truth.get("readable", "yes").lower() in {"no", "n", "false", "0"}
        if truly_unreadable:
            unreadable_total += 1
            nothing = all(v["value"] is None for v in rec["fields"].values())
            unreadable_flagged += int(not rec["readable"] or nothing)
        issues = check_record(rec, workers, today=date.today())
        doc_dangerous = False
        for f in FIELDS:
            t = None if truly_unreadable else truth_value(f, truth.get(f, ""))
            p = rec["fields"][f]["value"]
            outcome = classify(f, t, p)
            per_field[f][outcome] = per_field[f].get(outcome, 0) + 1
            rows.append({"file": file, "field": f, "truth": t, "pred": p, "outcome": outcome,
                         "confidence": rec["fields"][f].get("confidence")})
            if outcome in DANGEROUS:
                dangerous_total += 1
                doc_dangerous = True
                # A dangerous error is "caught" if validation flags the record for review.
                dangerous_caught += int(bool(issues))
        rec["_issues"] = issues
        rec["_has_dangerous"] = doc_dangerous

    n = len([r for r in rows if r["field"] == FIELDS[0]])
    acc = {f: sum(per_field[f].get(o, 0) for o in OK) / n if n else 0 for f in FIELDS}
    overall = sum(sum(per_field[f].get(o, 0) for o in OK) for f in FIELDS) / (n * len(FIELDS)) if n else 0
    return {
        "documents": n, "accuracy": acc, "overall": overall, "per_field": per_field, "rows": rows,
        "dangerous": dangerous_total, "dangerous_caught": dangerous_caught,
        "expiry_dangerous": sum(per_field["expiry_date"].get(o, 0) for o in DANGEROUS),
        "unreadable_total": unreadable_total, "unreadable_flagged": unreadable_flagged,
        "avg_latency": sum(latencies) / len(latencies) if latencies else 0,
    }


def mask(field: str, value):
    """Names are shown as initials so RESULTS.md can be committed without personal data."""
    if value is None:
        return "–"
    if field == "worker_name":
        return " ".join(t[0].upper() + "." for t in str(value).split() if t)
    return str(value)


def pct(x: float) -> str:
    return f"{x * 100:.0f}%"


def mark(outcome: str) -> str:
    return {"correct": "✅", "abstained_ok": "✅ (none)", "missed": "⚠️ missed",
            "wrong": "❌ wrong", "invented": "❌ invented"}[outcome]


def write_report(gt: dict, results: dict) -> str:
    methods = [m for m in METHODS if m in results]
    out = [
        "# Extraction experiment: Gemini vs Tesseract",
        "",
        f"_Generated by `experiments/evaluate.py` on {date.today().isoformat()}. "
        f"{len(gt)} documents in `ground_truth.csv`._",
        "",
        "Each field is compared with what is actually printed on the certificate. "
        "**Wrong** and **invented** values are dangerous (a wrong expiry date could mark an expired "
        "worker as valid). **Missed** values are safe failures: they go to manual review.",
        "",
        "## Summary",
        "",
        "| Metric | " + " | ".join(m.capitalize() for m in methods) + " |",
        "|---|" + "---|" * len(methods),
    ]

    def line(label, fn):
        out.append(f"| {label} | " + " | ".join(fn(results[m]) for m in methods) + " |")

    line("Documents evaluated", lambda r: str(r["documents"]))
    for f in FIELDS:
        line(f"{LABELS[f]} accuracy", lambda r, f=f: pct(r["accuracy"][f]))
    line("**All fields accuracy**", lambda r: f"**{pct(r['overall'])}**")
    line("**Wrong/invented expiry dates**", lambda r: f"**{r['expiry_dangerous']}**")
    line("Wrong/invented values (all fields)", lambda r: str(r["dangerous"]))
    line("…of which caught by validation rules",
         lambda r: f"{r['dangerous_caught']}/{r['dangerous']}" if r["dangerous"] else "–")
    line("Unreadable docs correctly flagged",
         lambda r: f"{r['unreadable_flagged']}/{r['unreadable_total']}" if r["unreadable_total"] else "–")
    line("Average time per document", lambda r: f"{r['avg_latency']:.1f} s")
    out.append("")

    # Suggested decision (the team still writes the final decision in docs/).
    if len(methods) == 2:
        a, b = (results[m] for m in methods)
        key = lambda m: (results[m]["expiry_dangerous"], results[m]["dangerous"] - results[m]["dangerous_caught"],
                         -results[m]["overall"])
        best = min(methods, key=key)
        out += ["## Suggested choice", "",
                f"Ranking rule: fewest wrong/invented expiry dates, then fewest dangerous errors that "
                f"validation would NOT catch, then highest overall accuracy → **{best}**.",
                "Check the per-document table before deciding; with 5–10 documents, one document can "
                "change the result.", ""]

    out += ["## Per-document results", ""]
    header = "| File | Field | On the document | " + " | ".join(m.capitalize() for m in methods) + " |"
    out += [header, "|---|---|---|" + "---|" * len(methods)]
    by_key = {m: {(r["file"], r["field"]): r for r in results[m]["rows"]} for m in methods}
    for file in gt:
        for f in FIELDS:
            cells = []
            truth = None
            for m in methods:
                r = by_key[m].get((file, f))
                if r is None:
                    cells.append("–")
                    continue
                truth = r["truth"]
                cells.append(f"{mask(f, r['pred'])} {mark(r['outcome'])}")
            if all(c == "–" for c in cells):
                continue
            out.append(f"| {file} | {LABELS[f]} | {mask(f, truth)} | " + " | ".join(cells) + " |")
    out.append("")

    out += ["## Validation flags per document", "",
            "Issues found by `validation.py` (any issue → status *needs review*).", "",
            "| File | " + " | ".join(m.capitalize() for m in methods) + " |",
            "|---|" + "---|" * len(methods)]
    for file in gt:
        cells = []
        for m in methods:
            rec = results[m].get("records", {}).get(file)
            cells.append("; ".join(rec["_issues"]) if rec and rec["_issues"] else "none")
        out.append(f"| {file} | " + " | ".join(cells) + " |")
    out.append("")
    return "\n".join(out)


def main() -> None:
    from common import GROUND_TRUTH
    if not GROUND_TRUTH.exists():
        raise SystemExit("Create experiments/ground_truth.csv first (copy ground_truth.example.csv)")
    gt = load_ground_truth()
    if not gt:
        raise SystemExit("ground_truth.csv has no rows (rows starting with # are ignored). Add one row per scan.")
    workers = load_workers()
    results = {}
    for m in METHODS:
        records = load_records(m)
        if not records:
            print(f"(no results for {m} — run run_{m}.py first)")
            continue
        missing = [f for f in gt if f not in records]
        if missing:
            print(f"warning: {m} has no result for {', '.join(missing)}")
        if len(missing) == len(gt):
            print(f"  -> none of the file names in ground_truth.csv match the {m} results "
                  f"({', '.join(sorted(records)[:4])} ...). Check the 'file' column.")
            continue
        r = evaluate(gt, records, workers)
        r["records"] = records
        results[m] = r
        print(f"{m:10s} overall {pct(r['overall'])}, wrong/invented expiry dates: {r['expiry_dangerous']}, "
              f"dangerous caught by validation: {r['dangerous_caught']}/{r['dangerous']}")
    if not results:
        raise SystemExit("Nothing to evaluate.")

    report = write_report(gt, results)
    (EXPERIMENT_DIR / "RESULTS.md").write_text(report, encoding="utf-8")
    summary = {m: {k: v for k, v in r.items() if k not in {"rows", "records"}} for m, r in results.items()}
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    (RESULTS_DIR / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print("Wrote experiments/RESULTS.md and experiments/results/summary.json")


if __name__ == "__main__":
    main()
